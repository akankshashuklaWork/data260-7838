"""Part 3.1: record the HUMAN helpfulness labels (1-5) for the 20 frozen drafts.

This is a plain terminal form: it shows one draft at a time and stores the number you type. The
labels must be your own judgement. They are not generated by a model and must not be changed after
you have seen any judge result.

    PYTHONPATH=code python -m hw10.label_drafts

Rubric (the same wording the judge's rubric uses, so both sides are measured the same way):

    1 = Not helpful: does not answer the question, is wrong, or contradicts the given facts
    2 = Weak: touches the topic but is mostly vague, partly wrong, or invents specifics
    3 = Fair: answers part of the question; some filler or a minor inaccuracy
    4 = Good: answers the question accurately and relevantly, small gaps
    5 = Excellent: accurate, relevant, concrete and clear; a renter could act on it directly

You can stop at any time (Ctrl-C or press Enter on a blank answer): progress is saved after every
label and the next run resumes where you stopped.
"""

from __future__ import annotations

import csv
import json
import textwrap

from .config import EVAL_CASES, HUMAN_LABELS

FIELDS = ["case_id", "human_score"]
RUBRIC = """Helpfulness scale (1-5):
  1 = Not helpful: does not answer the question, is wrong, or contradicts the given facts
  2 = Weak: touches the topic but is mostly vague, partly wrong, or invents specifics
  3 = Fair: answers part of the question; some filler or a minor inaccuracy
  4 = Good: answers the question accurately and relevantly, small gaps
  5 = Excellent: accurate, relevant, concrete and clear; a renter could act on it directly"""


def load_existing() -> dict[str, str]:
    if not HUMAN_LABELS.exists():
        return {}
    with open(HUMAN_LABELS, newline="", encoding="utf-8") as handle:
        return {row["case_id"]: row["human_score"] for row in csv.DictReader(handle)}


def save(labels: dict[str, str], order: list[str]) -> None:
    with open(HUMAN_LABELS, "w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=FIELDS)
        writer.writeheader()
        for case_id in order:
            if case_id in labels:
                writer.writerow({"case_id": case_id, "human_score": labels[case_id]})


def main() -> None:
    cases = json.loads(EVAL_CASES.read_text(encoding="utf-8"))
    order = [case["case_id"] for case in cases]
    labels = load_existing()
    print(RUBRIC)
    for case in cases:
        if case["case_id"] in labels:
            continue
        print("=" * 78)
        print(f"{case['case_id']}   ({len(labels)} of {len(cases)} labelled)")
        print("QUESTION:", case["question"])
        if case["context"]:
            print("FACTS GIVEN TO THE WRITER:", case["context"])
        print("DRAFT:")
        print(textwrap.fill(case["draft"], width=78, initial_indent="  ", subsequent_indent="  "))
        while True:
            try:
                answer = input("Your helpfulness score 1-5 (Enter to stop): ").strip()
            except (EOFError, KeyboardInterrupt):
                answer = ""
            if answer == "":
                save(labels, order)
                print(f"\nSaved {len(labels)} labels to {HUMAN_LABELS}")
                return
            if answer in {"1", "2", "3", "4", "5"}:
                labels[case["case_id"]] = answer
                save(labels, order)
                break
            print("  please type a whole number from 1 to 5")
    print(
        f"\nAll {len(labels)} labels saved to {HUMAN_LABELS}. Commit it before running the judge."
    )


if __name__ == "__main__":
    main()
